'use strict';

/**
 * Configuration, read once at boot from the environment (and an optional
 * server/.env file). No third-party env loader so the service has only
 * express + jspdf as dependencies.
 */

const fs = require('fs');
const path = require('path');

function loadEnvFile(file) {
  if (!fs.existsSync(file)) return;
  const text = fs.readFileSync(file, 'utf8');
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    const quoted =
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"));
    if (quoted) value = value.slice(1, -1);
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnvFile(path.join(__dirname, '..', '.env'));

const int = (value, fallback) => {
  const n = parseInt(value, 10);
  return Number.isFinite(n) ? n : fallback;
};

const list = (value, fallback) =>
  String(value == null ? fallback : value)
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);

const config = {
  port: int(process.env.PORT, 3000),
  host: process.env.HOST || '0.0.0.0',
  env: process.env.NODE_ENV || 'development',
  version: require('../package.json').version,

  apiKeys: list(process.env.RESUME_API_KEYS, ''),
  corsOrigins: list(process.env.RESUME_CORS_ORIGINS, '*'),

  rateWindowMs: int(process.env.RESUME_RATE_WINDOW_MS, 60000),
  rateMax: int(process.env.RESUME_RATE_MAX, 60),

  maxBody: process.env.RESUME_MAX_BODY || '256kb',
  defaultTemplate: process.env.RESUME_DEFAULT_TEMPLATE || 'classic',
  footerText: process.env.RESUME_FOOTER_TEXT || 'Generated by Resume Builder',
};

// Open mode when no keys are configured: anybody can call the API, protected
// only by the per-IP rate limit.
config.authRequired = config.apiKeys.length > 0;

module.exports = config;
